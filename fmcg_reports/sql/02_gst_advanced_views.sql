-- ----------------------------------------------------------------
-- A1. HSN WISE SALES REPORT
-- Purpose: GSTR-1 table 12 - HSN summary of outward supplies
-- ----------------------------------------------------------------
IF OBJECT_ID('dbo.VW_GST_HSN_SALES','V') IS NOT NULL DROP VIEW dbo.VW_GST_HSN_SALES
GO
CREATE VIEW dbo.VW_GST_HSN_SALES AS
SELECT
    D.SD_DEPT_CODE                                          AS DEPT_CODE,
    DATEPART(YEAR,  H.BILL_DATE)                           AS FIN_YEAR,
    DATEPART(MONTH, H.BILL_DATE)                           AS TAX_MONTH,
    DATENAME(MONTH, H.BILL_DATE)                           AS MONTH_NAME,
    ISNULL(D.HSNSACCODE, 'UNCLASSIFIED')                   AS HSN_CODE,
    ISNULL(I.HSN_CODE,d.HSNSACCODE)                       AS ITEM_HSN,
    MAX(I.CONS_UOM)                                        AS UOM,
    COUNT(DISTINCT H.BILL_NO)                              AS BILL_COUNT,
    SUM(ISNULL(D.QTY,0))                                   AS TOTAL_QTY,
    SUM(ISNULL(D.AMOUNT,0) + ISNULL(D.DISC_AMOUNT,0))     AS TAXABLE_VALUE,  -- before disc
    SUM(ISNULL(D.DISC_AMOUNT,0))                           AS TOTAL_DISCOUNT,
    SUM(ISNULL(D.AMOUNT,0))                                AS NET_TAXABLE_VALUE,
    -- GST split (IGST / CGST+SGST based on TAX_TYPE)
    SUM(CASE WHEN ISNULL(D.TAX_TYPE,'') IN ('IGST','I') THEN ISNULL(CAST(D.TAX_AMOUNT AS MONEY),0) ELSE 0 END) AS IGST_AMT,
    SUM(CASE WHEN ISNULL(D.TAX_TYPE,'') NOT IN ('IGST','I') THEN ISNULL(CAST(D.TAX_AMOUNT AS MONEY),0)/2 ELSE 0 END) AS CGST_AMT,
    SUM(CASE WHEN ISNULL(D.TAX_TYPE,'') NOT IN ('IGST','I') THEN ISNULL(CAST(D.TAX_AMOUNT AS MONEY),0)/2 ELSE 0 END) AS SGST_AMT,
    SUM(ISNULL(CAST(D.CESS_AMOUNT AS MONEY),0))           AS CESS_AMT,
    SUM(ISNULL(CAST(D.TAX_AMOUNT AS MONEY),0))            AS TOTAL_TAX,
    SUM(ISNULL(D.AMOUNT,0) + ISNULL(CAST(D.TAX_AMOUNT AS MONEY),0)) AS TOTAL_VALUE,
    MAX(D.TAX_PERCENT)                                     AS GST_RATE
FROM dbo.SALES_HDR H
INNER JOIN dbo.SALES_DTL D ON H.BILL_NO=D.BILL_NO AND H.SH_DEPT_CODE=D.SD_DEPT_CODE
LEFT  JOIN dbo.ITEM_MST I  ON D.SERVICEORPRODUCTCODE=I.ITEM_CODE
WHERE ISNULL(H.ISCANCELLED,0)=0
  AND D.SALES_ITEM_TYPE='P'
GROUP BY D.SD_DEPT_CODE, DATEPART(YEAR,H.BILL_DATE), DATEPART(MONTH,H.BILL_DATE),
         DATENAME(MONTH,H.BILL_DATE),   ISNULL(I.HSN_CODE,d.HSNSACCODE) ,D.HSNSACCODE
GO

-- ----------------------------------------------------------------
-- A2. HSN WISE PURCHASE REPORT
-- Purpose: GSTR-2 / ITC reconciliation, purchase HSN summary
-- ----------------------------------------------------------------
IF OBJECT_ID('dbo.VW_GST_HSN_PURCHASE','V') IS NOT NULL DROP VIEW dbo.VW_GST_HSN_PURCHASE
GO
CREATE VIEW dbo.VW_GST_HSN_PURCHASE AS
SELECT
    H.GH_DEPT_CODE                                          AS DEPT_CODE,
    DATEPART(YEAR,  H.GRN_DATE)                            AS FIN_YEAR,
    DATEPART(MONTH, H.GRN_DATE)                            AS TAX_MONTH,
    DATENAME(MONTH, H.GRN_DATE)                            AS MONTH_NAME,
    ISNULL(D.HSNSACCODE,'UNCLASSIFIED')                    AS HSN_CODE,
    MAX(ISNULL(I.CONS_UOM,'UNT'))                          AS UOM,
    S.SUPPLIER_NAME,
    S.GSTIN_NO                                              AS SUPPLIER_GSTIN,
    COUNT(DISTINCT H.GRN_NO)                               AS GRN_COUNT,
    SUM(ISNULL(D.REC_QTY,0))                              AS TOTAL_QTY,
    SUM(ISNULL(D.AMOUNT,0))                               AS TAXABLE_VALUE,
    SUM(ISNULL(D.TAX_AMOUNT,0))                           AS TOTAL_TAX,
    SUM(CASE WHEN ISNULL(D.TAX_AMOUNT,0)>0
             THEN ISNULL(D.TAX_AMOUNT,0)/2 ELSE 0 END)    AS CGST_AMT,
    SUM(CASE WHEN ISNULL(D.TAX_AMOUNT,0)>0
             THEN ISNULL(D.TAX_AMOUNT,0)/2 ELSE 0 END)    AS SGST_AMT,
    SUM(ISNULL(CAST(D.CESS_AMOUNT AS MONEY),0))           AS CESS_AMT,
    SUM(ISNULL(D.AMOUNT,0) + ISNULL(D.TAX_AMOUNT,0))     AS TOTAL_VALUE,
    MAX(D.TAX_PERCENT)                                     AS GST_RATE,
    CASE WHEN S.GSTIN_NO IS NOT NULL AND LEN(ISNULL(S.GSTIN_NO,''))=15
         THEN 'ELIGIBLE' ELSE 'INELIGIBLE' END             AS ITC_STATUS
FROM dbo.GRN_HDR H
INNER JOIN dbo.GRN_DTL D      ON H.GRN_NO=D.GRN_NO AND H.GH_DEPT_CODE=D.GD_DEPT_CODE
LEFT  JOIN dbo.ITEM_MST I     ON D.ITEM_CODE=I.ITEM_CODE
LEFT  JOIN dbo.SUPPLIER_MST S ON H.SUPPLIERCODE=S.SUPPLIER_CODE
WHERE ISNULL(H.ISCANCELLED,0)=0
GROUP BY H.GH_DEPT_CODE, DATEPART(YEAR,H.GRN_DATE), DATEPART(MONTH,H.GRN_DATE),
         DATENAME(MONTH,H.GRN_DATE), ISNULL(D.HSNSACCODE,'UNCLASSIFIED'),
         S.SUPPLIER_NAME, S.GSTIN_NO
GO

-- ----------------------------------------------------------------
-- A3. GSTR-1 REPORT VIEW
-- B2B: registered buyers | B2C: unregistered | CDNR: credit/debit notes
-- ----------------------------------------------------------------
IF OBJECT_ID('dbo.VW_GST_GSTR1','V') IS NOT NULL DROP VIEW dbo.VW_GST_GSTR1
GO
CREATE VIEW dbo.VW_GST_GSTR1 AS
SELECT
    H.SH_DEPT_CODE                                          AS DEPT_CODE,
    DATEPART(YEAR,  H.BILL_DATE)                           AS FIN_YEAR,
    DATEPART(MONTH, H.BILL_DATE)                           AS TAX_MONTH,
    DATENAME(MONTH, H.BILL_DATE)                           AS MONTH_NAME,
    H.BILL_NO                                               AS BILL_NO,
    CONVERT(DATE, H.BILL_DATE)                             AS BILL_DATE,
    H.GSTBILLNO                                             AS GST_INVOICE_NO,
    H.TRANSACTION_TYPE                                      AS INVOICE_TYPE,
    H.CUSTOMER_CODE,
    H.CUSTOMER                                              AS CUSTOMER_NAME,
    CM.OFFICE1_STATE                                        AS CUSTOMER_STATE,
    -- Invoice category: B2B / B2CS / B2CL / EXP
    CASE
        WHEN H.INVOICE_TPE IN ('EXPORT','EXP')              THEN 'EXP'
        WHEN CM.GSTIN_NO IS NOT NULL AND CM.GSTIN_NO <> '' THEN 'B2B'
        WHEN ISNULL(H.GRAND_TOTAL,0) >= 250000              THEN 'B2CL'
        ELSE 'B2CS'
    END                                                     AS INVOICE_CATEGORY,
    ISNULL(H.SUBTOTAL_AMOUNT,0)                            AS TAXABLE_VALUE,
    -- Tax amounts with expected column names
    SUM(CASE WHEN ISNULL(D.TAX_TYPE,'') IN ('IGST','I')
             THEN ISNULL(CAST(D.TAX_AMOUNT AS MONEY),0) ELSE 0 END) AS IGST_AMT,
    SUM(CASE WHEN ISNULL(D.TAX_TYPE,'') NOT IN ('IGST','I')
             THEN ISNULL(CAST(D.TAX_AMOUNT AS MONEY),0)/2 ELSE 0 END) AS CGST_AMT,
    SUM(CASE WHEN ISNULL(D.TAX_TYPE,'') NOT IN ('IGST','I')
             THEN ISNULL(CAST(D.TAX_AMOUNT AS MONEY),0)/2 ELSE 0 END) AS SGST_AMT,
    SUM(ISNULL(CAST(D.CESS_AMOUNT AS MONEY),0))           AS CESS_AMT,
    SUM(ISNULL(CAST(D.TAX_AMOUNT AS MONEY),0))            AS TOTAL_TAX,
    ISNULL(H.GRAND_TOTAL,0)                               AS INVOICE_VALUE
FROM dbo.SALES_HDR H
INNER JOIN dbo.SALES_DTL D ON H.BILL_NO=D.BILL_NO AND H.SH_DEPT_CODE=D.SD_DEPT_CODE
LEFT  JOIN dbo.CUSTOMER_MST CM ON H.CUSTOMER_CODE=CM.CUSTOMER_CODE
WHERE ISNULL(H.ISCANCELLED,0)=0
GROUP BY H.SH_DEPT_CODE, H.BILL_NO, H.BILL_DATE, H.GSTBILLNO,
         H.CUSTOMER_CODE, H.CUSTOMER, CM.OFFICE1_STATE, CM.CUSTOMER_CODE,
         CM.GSTIN_NO, H.INVOICE_TPE, H.SUBTOTAL_AMOUNT,
         H.GRAND_TOTAL, H.TRANSACTION_TYPE, H.POSID
GO

-- ----------------------------------------------------------------
-- A4. GSTR-3B SUMMARY VIEW
-- Table 3.1: Outward supplies | Table 4: ITC available
-- ----------------------------------------------------------------
IF OBJECT_ID('dbo.VW_GST_GSTR3B','V') IS NOT NULL DROP VIEW dbo.VW_GST_GSTR3B
GO
CREATE VIEW dbo.VW_GST_GSTR3B AS
WITH SALES_TAX AS (
    SELECT
        H.SH_DEPT_CODE AS DEPT_CODE,
        DATEPART(YEAR,  H.BILL_DATE) AS FIN_YEAR,
        DATEPART(MONTH, H.BILL_DATE) AS TAX_MONTH,
        DATENAME(MONTH, H.BILL_DATE) AS MONTH_NAME,
        -- 3.1(a) Taxable outward supplies
        SUM(ISNULL(D.AMOUNT,0))  AS TAXABLE_OUTWARD,
        SUM(CASE WHEN D.TAX_TYPE IN ('IGST','I') THEN ISNULL(CAST(D.TAX_AMOUNT AS MONEY),0) ELSE 0 END) AS IGST_SALES,
        SUM(CASE WHEN D.TAX_TYPE NOT IN ('IGST','I') THEN ISNULL(CAST(D.TAX_AMOUNT AS MONEY),0)/2 ELSE 0 END) AS CGST_SALES,
        SUM(CASE WHEN D.TAX_TYPE NOT IN ('IGST','I') THEN ISNULL(CAST(D.TAX_AMOUNT AS MONEY),0)/2 ELSE 0 END) AS SGST_SALES,
        SUM(ISNULL(CAST(D.CESS_AMOUNT AS MONEY),0)) AS CESS_SALES,
        -- 3.1(c) Nil/exempt
        SUM(CASE WHEN ISNULL(D.TAX_PERCENT,0)=0 THEN ISNULL(D.AMOUNT,0) ELSE 0 END) AS NIL_RATED_SALES
    FROM dbo.SALES_HDR H
    INNER JOIN dbo.SALES_DTL D ON H.BILL_NO=D.BILL_NO AND H.SH_DEPT_CODE=D.SD_DEPT_CODE
    WHERE ISNULL(H.ISCANCELLED,0)=0 AND D.SALES_ITEM_TYPE='P'
    GROUP BY H.SH_DEPT_CODE, DATEPART(YEAR,H.BILL_DATE), DATEPART(MONTH,H.BILL_DATE), DATENAME(MONTH,H.BILL_DATE)
),
PURCHASE_TAX AS (
    SELECT
        H.GH_DEPT_CODE AS DEPT_CODE,
        DATEPART(YEAR,  H.GRN_DATE) AS FIN_YEAR,
        DATEPART(MONTH, H.GRN_DATE) AS TAX_MONTH,
        -- 4: ITC eligible (supplier has valid GSTIN)
        SUM(CASE WHEN S.GSTIN_NO IS NOT NULL AND LEN(ISNULL(S.GSTIN_NO,''))=15
                 THEN ISNULL(D.TAX_AMOUNT,0) ELSE 0 END) AS ITC_ELIGIBLE,
        SUM(CASE WHEN S.GSTIN_NO IS NULL OR LEN(ISNULL(S.GSTIN_NO,''))<>15
                 THEN ISNULL(D.TAX_AMOUNT,0) ELSE 0 END) AS ITC_INELIGIBLE,
        SUM(ISNULL(D.TAX_AMOUNT,0)/2) AS ITC_CGST,
        SUM(ISNULL(D.TAX_AMOUNT,0)/2) AS ITC_SGST
    FROM dbo.GRN_HDR H
    INNER JOIN dbo.GRN_DTL D    ON H.GRN_NO=D.GRN_NO AND H.GH_DEPT_CODE=D.GD_DEPT_CODE
    LEFT  JOIN dbo.SUPPLIER_MST S ON H.SUPPLIERCODE=S.SUPPLIER_CODE
    WHERE ISNULL(H.ISCANCELLED,0)=0
    GROUP BY H.GH_DEPT_CODE, DATEPART(YEAR,H.GRN_DATE), DATEPART(MONTH,H.GRN_DATE)
),
RETURNS_TAX AS (
    SELECT
        RH.SRH_DEPT_CODE AS DEPT_CODE,
        DATEPART(YEAR,  RH.BILL_RTN_DATE) AS FIN_YEAR,
        DATEPART(MONTH, RH.BILL_RTN_DATE) AS TAX_MONTH,
        SUM(ISNULL(RH.GRAND_TOTAL,0)) AS RETURN_VALUE,
        SUM(ISNULL(CAST(RD.TAX_AMOUNT AS MONEY),0)) AS RETURN_TAX
    FROM dbo.SALES_RETURN_HDR RH
    INNER JOIN dbo.SALES_RETURN_DTL RD ON RH.BILL_RTN_NO=RD.BILL_RTN_NO AND RH.SRH_DEPT_CODE=RD.SRD_DEPT_CODE
    GROUP BY RH.SRH_DEPT_CODE, DATEPART(YEAR,RH.BILL_RTN_DATE), DATEPART(MONTH,RH.BILL_RTN_DATE)
)
SELECT
    S.DEPT_CODE, S.FIN_YEAR, S.TAX_MONTH, S.MONTH_NAME,
    -- 3.1 Outward
    S.TAXABLE_OUTWARD,
    S.IGST_SALES, S.CGST_SALES, S.SGST_SALES, S.CESS_SALES,
    S.IGST_SALES+S.CGST_SALES+S.SGST_SALES+S.CESS_SALES AS TOTAL_OUTPUT_TAX,
    S.NIL_RATED_SALES,
    -- Returns (3.1 deduction)
    ISNULL(R.RETURN_VALUE,0)   AS RETURN_VALUE,
    ISNULL(R.RETURN_TAX,0)     AS RETURN_TAX_CREDIT,
    -- 4: ITC
    ISNULL(P.ITC_ELIGIBLE,0)   AS ITC_ELIGIBLE,
    ISNULL(P.ITC_INELIGIBLE,0) AS ITC_INELIGIBLE,
    ISNULL(P.ITC_CGST,0)       AS ITC_CGST,
    ISNULL(P.ITC_SGST,0)       AS ITC_SGST,
    -- Net liability
    (S.IGST_SALES+S.CGST_SALES+S.SGST_SALES+S.CESS_SALES)
    - ISNULL(R.RETURN_TAX,0)
    - ISNULL(P.ITC_ELIGIBLE,0)  AS NET_TAX_LIABILITY
FROM SALES_TAX S
LEFT JOIN PURCHASE_TAX P ON S.DEPT_CODE=P.DEPT_CODE AND S.FIN_YEAR=P.FIN_YEAR AND S.TAX_MONTH=P.TAX_MONTH
LEFT JOIN RETURNS_TAX  R ON S.DEPT_CODE=R.DEPT_CODE AND S.FIN_YEAR=R.FIN_YEAR AND S.TAX_MONTH=R.TAX_MONTH
GO

-- ----------------------------------------------------------------
-- A5. INPUT TAX CREDIT (ITC) DETAIL VIEW
-- ----------------------------------------------------------------
IF OBJECT_ID('dbo.VW_GST_ITC_DETAIL','V') IS NOT NULL DROP VIEW dbo.VW_GST_ITC_DETAIL
GO
CREATE VIEW dbo.VW_GST_ITC_DETAIL AS
SELECT
    H.GH_DEPT_CODE                           AS DEPT_CODE,
    H.GRN_NO,
    CONVERT(DATE, H.GRN_DATE)              AS GRN_DATE,
    DATEPART(YEAR,  H.GRN_DATE)            AS FIN_YEAR,
    DATEPART(MONTH, H.GRN_DATE)            AS TAX_MONTH,
    DATENAME(MONTH, H.GRN_DATE)            AS MONTH_NAME,
    H.INVOICENO                              AS SUPPLIER_INVOICE,
    CONVERT(DATE, H.INVOICE_DATE)          AS INVOICE_DATE,
    S.SUPPLIER_CODE                          AS SUPPLIERCODE,
    S.SUPPLIER_NAME,
    S.GSTIN_NO                               AS SUPPLIER_GSTIN,
    S.PAN_NO                                 AS SUPPLIER_PAN,
    D.ITEM_CODE,
    I.ITEM_NAME,
    ISNULL(D.HSNSACCODE,'')                AS HSN_CODE,
    D.TAX_PERCENT                            AS GST_RATE,
    ISNULL(D.REC_QTY,0)                    AS QTY,
    ISNULL(D.AMOUNT,0)                      AS TAXABLE_VALUE,
    ISNULL(D.TAX_AMOUNT,0)                 AS TOTAL_TAX,
    ISNULL(D.TAX_AMOUNT,0)/2               AS CGST_ITC,
    ISNULL(D.TAX_AMOUNT,0)/2               AS SGST_ITC,
    ISNULL(CAST(D.CESS_AMOUNT AS MONEY),0)  AS CESS_ITC,
    -- ITC eligibility
    CASE WHEN LEN(ISNULL(S.GSTIN_NO,''))=15 THEN 'ELIGIBLE'
         WHEN ISNULL(S.GSTIN_NO,'')=''       THEN 'INELIGIBLE - NO GSTIN'
         ELSE 'INELIGIBLE - INVALID GSTIN'
    END                                      AS ITC_ELIGIBILITY,
    CASE WHEN LEN(ISNULL(S.GSTIN_NO,''))=15
         THEN ISNULL(D.TAX_AMOUNT,0) ELSE 0 END  AS ELIGIBLE_ITC,
    CASE WHEN LEN(ISNULL(S.GSTIN_NO,''))!=15
         THEN ISNULL(D.TAX_AMOUNT,0) ELSE 0 END  AS INELIGIBLE_ITC,
    -- Validation flags
    CASE WHEN H.INVOICE_DATE IS NULL              THEN 'MISSING INVOICE DATE'
         WHEN H.INVOICENO IS NULL OR H.INVOICENO='' THEN 'MISSING INVOICE NO'
         WHEN S.GSTIN_NO IS NULL                  THEN 'SUPPLIER GSTIN MISSING'
         ELSE 'OK' END                            AS VALIDATION_STATUS
FROM dbo.GRN_HDR H
INNER JOIN dbo.GRN_DTL D      ON H.GRN_NO=D.GRN_NO AND H.GH_DEPT_CODE=D.GD_DEPT_CODE
LEFT  JOIN dbo.SUPPLIER_MST S ON H.SUPPLIERCODE=S.SUPPLIER_CODE
LEFT  JOIN dbo.ITEM_MST I     ON D.ITEM_CODE=I.ITEM_CODE
WHERE ISNULL(H.ISCANCELLED,0)=0
GO

-- ----------------------------------------------------------------
-- A6. SALES RETURN (CDNR) VIEW - Credit/Debit Notes for GSTR-1
-- ----------------------------------------------------------------
IF OBJECT_ID('dbo.VW_GST_CDNR','V') IS NOT NULL DROP VIEW dbo.VW_GST_CDNR
GO
CREATE VIEW dbo.VW_GST_CDNR AS
SELECT
    RH.SRH_DEPT_CODE                        AS DEPT_CODE,
    RH.BILL_RTN_NO                          AS NOTE_NO,
    CONVERT(DATE, RH.BILL_RTN_DATE)        AS NOTE_DATE,
    DATEPART(YEAR,  RH.BILL_RTN_DATE)      AS FIN_YEAR,
    DATEPART(MONTH, RH.BILL_RTN_DATE)      AS TAX_MONTH,
    RH.AGAINST_BILL_NO                      AS ORIGINAL_INVOICE,
    'C'                                     AS NOTE_TYPE,  -- C=Credit, D=Debit
    SH.CUSTOMER_CODE,
    SH.CUSTOMER                             AS CUSTOMER_NAME,
    ISNULL(RH.GRAND_TOTAL,0)              AS NOTE_VALUE,
    ISNULL(RH.SUBTOTAL_AMOUNT,0)          AS TAXABLE_VALUE,
    SUM(ISNULL(CAST(RD.TAX_AMOUNT AS MONEY),0)) AS TOTAL_GST,
    SUM(CASE WHEN ISNULL(RD.TAX_TYPE,'') NOT IN ('IGST','I')
             THEN ISNULL(CAST(RD.TAX_AMOUNT AS MONEY),0)/2 ELSE 0 END) AS CGST,
    SUM(CASE WHEN ISNULL(RD.TAX_TYPE,'') NOT IN ('IGST','I')
             THEN ISNULL(CAST(RD.TAX_AMOUNT AS MONEY),0)/2 ELSE 0 END) AS SGST,
    SUM(CASE WHEN ISNULL(RD.TAX_TYPE,'') IN ('IGST','I')
             THEN ISNULL(CAST(RD.TAX_AMOUNT AS MONEY),0) ELSE 0 END) AS IGST,
    RH.REASON_FOR_REFUND
FROM dbo.SALES_RETURN_HDR RH
INNER JOIN dbo.SALES_RETURN_DTL RD ON RH.BILL_RTN_NO=RD.BILL_RTN_NO AND RH.SRH_DEPT_CODE=RD.SRD_DEPT_CODE
LEFT  JOIN dbo.SALES_HDR SH        ON RH.AGAINST_BILL_NO=SH.BILL_NO
GROUP BY RH.SRH_DEPT_CODE, RH.BILL_RTN_NO, RH.BILL_RTN_DATE, RH.AGAINST_BILL_NO,
         SH.CUSTOMER_CODE, SH.CUSTOMER, RH.GRAND_TOTAL, RH.SUBTOTAL_AMOUNT, RH.REASON_FOR_REFUND
GO


