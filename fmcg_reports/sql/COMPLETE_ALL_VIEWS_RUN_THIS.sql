-- ────────────────────────────────────────────────────────────────
-- 28. EXCEPTIONS (negative stock, abnormal sales, cancelled bills)
-- ────────────────────────────────────────────────────────────────
IF OBJECT_ID('dbo.VW_RPT_EXCEPTIONS','V') IS NOT NULL DROP VIEW dbo.VW_RPT_EXCEPTIONS
GO
CREATE VIEW dbo.VW_RPT_EXCEPTIONS AS
-- Negative / zero stock items
SELECT
    'NEGATIVE STOCK'                   AS EXCEPTION_TYPE,
    'HIGH'                             AS SEVERITY,
    CAST(ITEM_CODE AS VARCHAR)         AS REFERENCE_NO,
    ITEM_NAME                          AS DESCRIPTION,
    CAST(QOH AS VARCHAR)               AS AMOUNT_STR,
    GETDATE()                          AS EXCEPTION_DATE,
    NULL                               AS DEPT_CODE
FROM dbo.ITEM_MST
WHERE ISNULL(QOH,0)<0 AND ISNULL(Discontinue,0)=0
UNION ALL
-- High value cancelled bills
SELECT
    'CANCELLED HIGH VALUE BILL',
    'HIGH',
    CAST(BILL_NO AS VARCHAR),
    'Bill cancelled: ' + ISNULL(REASON_FOR_CANCELLATION,'No reason'),
    CAST(ISNULL(GRAND_TOTAL,0) AS VARCHAR),
    CANCELLED_DATE,
    SH_DEPT_CODE
FROM dbo.SALES_HDR
WHERE ISNULL(ISCANCELLED,0)=1 AND ISNULL(GRAND_TOTAL,0)>5000
UNION ALL
-- Items with stock below reorder
SELECT
    'REORDER ALERT',
    'MEDIUM',
    CAST(ITEM_CODE AS VARCHAR),
    ITEM_NAME,
    'QOH:' + CAST(ISNULL(QOH,0) AS VARCHAR) + ' REORDER:' + CAST(ISNULL(REORDER_LVL,0) AS VARCHAR),
    GETDATE(),
    NULL
FROM dbo.ITEM_MST
WHERE ISNULL(QOH,0)<=ISNULL(REORDER_LVL,0) AND ISNULL(REORDER_LVL,0)>0
  AND ISNULL(Discontinue,0)=0
GO

-- ────────────────────────────────────────────────────────────────
-- 29. STOCK VALUATION
-- ────────────────────────────────────────────────────────────────
IF OBJECT_ID('dbo.VW_RPT_STOCK_VALUATION','V') IS NOT NULL DROP VIEW dbo.VW_RPT_STOCK_VALUATION
GO
CREATE VIEW dbo.VW_RPT_STOCK_VALUATION AS
SELECT
    I.ITEM_CODE,
    I.ITEM_NAME,
    I.EAN_CODE,
    CAT.Category_Desc                  AS CATEGORY,
    BRD.Brand_Name                     AS BRAND,
    S.SUPPLIER_NAME,
    ISNULL(I.QOH,0)                   AS QTY_ON_HAND,
    ISNULL(I.CP,0)                    AS COST_PRICE,
    ISNULL(I.MRP,0)                   AS MRP,
    ISNULL(I.SP,0)                    AS SALE_PRICE,
    ISNULL(I.QOH,0)*ISNULL(I.CP,0)   AS VALUE_AT_COST,
    ISNULL(I.QOH,0)*ISNULL(I.MRP,0)  AS VALUE_AT_MRP,
    ISNULL(I.QOH,0)*ISNULL(I.SP,0)   AS VALUE_AT_SP,
    (ISNULL(I.QOH,0)*ISNULL(I.SP,0)) -
    (ISNULL(I.QOH,0)*ISNULL(I.CP,0)) AS POTENTIAL_PROFIT,
    I.HSN_CODE,
    I.EXP_DATE                         AS EXPIRY_DATE,
    CASE WHEN I.EXP_DATE IS NOT NULL AND I.EXP_DATE<GETDATE() THEN 'EXPIRED'
         WHEN I.EXP_DATE IS NOT NULL AND I.EXP_DATE<DATEADD(DAY,30,GETDATE()) THEN 'EXPIRING SOON'
         ELSE 'OK' END AS EXPIRY_STATUS
FROM dbo.ITEM_MST I
LEFT JOIN dbo.Category_Mst CAT  ON I.CATEGORY_CODE=CAT.Category_Code
LEFT JOIN dbo.Brand_Master BRD  ON I.BRAND_CODE=BRD.Brand_Code
LEFT JOIN dbo.SUPPLIER_MST S    ON I.SUPPLIER_CODE=S.SUPPLIER_CODE
WHERE ISNULL(I.Discontinue,0)=0 AND ISNULL(I.QOH,0)>0
GO

-- ────────────────────────────────────────────────────────────────
-- 30. LIVE DASHBOARD SUMMARY
-- ────────────────────────────────────────────────────────────────
IF OBJECT_ID('dbo.VW_RPT_DASHBOARD','V') IS NOT NULL DROP VIEW dbo.VW_RPT_DASHBOARD
GO
CREATE VIEW dbo.VW_RPT_DASHBOARD AS
SELECT
    CAST(GETDATE() AS DATE)            AS REPORT_DATE,
    -- Today sales
    (SELECT COUNT(*) FROM dbo.SALES_HDR WHERE CONVERT(DATE,BILL_DATE)=CAST(GETDATE() AS DATE) AND ISNULL(ISCANCELLED,0)=0) AS TODAY_BILLS,
    (SELECT ISNULL(SUM(GRAND_TOTAL),0) FROM dbo.SALES_HDR WHERE CONVERT(DATE,BILL_DATE)=CAST(GETDATE() AS DATE) AND ISNULL(ISCANCELLED,0)=0) AS TODAY_SALES,
    (SELECT ISNULL(SUM(DISC_AMOUNT),0) FROM dbo.SALES_HDR WHERE CONVERT(DATE,BILL_DATE)=CAST(GETDATE() AS DATE) AND ISNULL(ISCANCELLED,0)=0) AS TODAY_DISCOUNT,
    -- This month
    (SELECT ISNULL(SUM(GRAND_TOTAL),0) FROM dbo.SALES_HDR WHERE YEAR(BILL_DATE)=YEAR(GETDATE()) AND MONTH(BILL_DATE)=MONTH(GETDATE()) AND ISNULL(ISCANCELLED,0)=0) AS MTD_SALES,
    (SELECT COUNT(*) FROM dbo.SALES_HDR WHERE YEAR(BILL_DATE)=YEAR(GETDATE()) AND MONTH(BILL_DATE)=MONTH(GETDATE()) AND ISNULL(ISCANCELLED,0)=0) AS MTD_BILLS,
    -- Stock
    (SELECT COUNT(*) FROM dbo.ITEM_MST WHERE ISNULL(QOH,0)<=0 AND ISNULL(Discontinue,0)=0) AS OUT_OF_STOCK_COUNT,
    (SELECT COUNT(*) FROM dbo.ITEM_MST WHERE ISNULL(QOH,0)<=ISNULL(REORDER_LVL,0) AND ISNULL(REORDER_LVL,0)>0 AND ISNULL(Discontinue,0)=0) AS REORDER_COUNT,
    (SELECT ISNULL(SUM(ISNULL(QOH,0)*ISNULL(CP,0)),0) FROM dbo.ITEM_MST WHERE ISNULL(Discontinue,0)=0) AS TOTAL_STOCK_VALUE,
    -- Customers
    (SELECT COUNT(*) FROM dbo.CUSTOMER_MST) AS TOTAL_CUSTOMERS,
    -- Purchases this month
    (SELECT ISNULL(SUM(GRANDTOTAL),0) FROM dbo.GRN_HDR WHERE YEAR(GRN_DATE)=YEAR(GETDATE()) AND MONTH(GRN_DATE)=MONTH(GETDATE()) AND ISNULL(ISCANCELLED,0)=0) AS MTD_PURCHASE
GO

