-- ----------------------------------------------------------------
-- B2. CUSTOMER SEGMENTATION & INTELLIGENCE VIEW
-- RFM: Recency, Frequency, Monetary scoring
-- ----------------------------------------------------------------
IF OBJECT_ID('dbo.VW_RPT_CUSTOMER_SEGMENTS','V') IS NOT NULL DROP VIEW dbo.VW_RPT_CUSTOMER_SEGMENTS
GO
CREATE VIEW dbo.VW_RPT_CUSTOMER_SEGMENTS AS
WITH BASE AS (
    SELECT
        H.CUSTOMER_CODE,
        CM.CUSTOMER_NAME,
        CM.OFFICE1_PHONE                        AS MOBILE,
        CM.OFFICE1_EMAIL_ID                     AS EMAIL,
        CM.OFFICE1_CITY                         AS CITY,
        CM.OFFICE1_STATE                        AS STATE,
        ISNULL(CM.VIP_CUSTOMER,0)             AS IS_VIP,
        CM.DATEOFBIRTH,
        CM.CARD_TYPE,
        ISNULL(CM.BALANCE_POINTS,0)           AS LOYALTY_POINTS,
        CONVERT(DATE, CM.Last_Visit)           AS LAST_VISIT,
        CONVERT(DATE, CM.First_Visit)          AS FIRST_VISIT,
        DATEDIFF(DAY, CM.Last_Visit, GETDATE()) AS DAYS_INACTIVE,
        COUNT(H.BILL_NO)                       AS TOTAL_VISITS,
        SUM(ISNULL(H.GRAND_TOTAL,0))          AS LIFETIME_VALUE,
        AVG(ISNULL(H.GRAND_TOTAL,0))          AS AVG_BILL_VALUE,
        MAX(ISNULL(H.GRAND_TOTAL,0))          AS MAX_BILL,
        MIN(CONVERT(DATE, H.BILL_DATE))        AS FIRST_PURCHASE,
        MAX(CONVERT(DATE, H.BILL_DATE))        AS LAST_PURCHASE
    FROM dbo.CUSTOMER_MST CM
    LEFT JOIN dbo.SALES_HDR H ON CM.CUSTOMER_CODE=H.CUSTOMER_CODE AND ISNULL(H.ISCANCELLED,0)=0
    GROUP BY H.CUSTOMER_CODE, CM.CUSTOMER_NAME, CM.OFFICE1_PHONE, CM.OFFICE1_EMAIL_ID,
             CM.OFFICE1_CITY, CM.OFFICE1_STATE, CM.VIP_CUSTOMER, CM.DATEOFBIRTH,
             CM.CARD_TYPE, CM.BALANCE_POINTS, CM.Last_Visit, CM.First_Visit
)
SELECT *,
    -- RFM Scores (1-5 scale)
    CASE WHEN DAYS_INACTIVE <= 30  THEN 5
         WHEN DAYS_INACTIVE <= 60  THEN 4
         WHEN DAYS_INACTIVE <= 90  THEN 3
         WHEN DAYS_INACTIVE <= 180 THEN 2 ELSE 1 END          AS R_SCORE,
    CASE WHEN TOTAL_VISITS >= 24 THEN 5
         WHEN TOTAL_VISITS >= 12 THEN 4
         WHEN TOTAL_VISITS >= 6  THEN 3
         WHEN TOTAL_VISITS >= 2  THEN 2 ELSE 1 END             AS F_SCORE,
    CASE WHEN LIFETIME_VALUE >= 100000 THEN 5
         WHEN LIFETIME_VALUE >= 50000  THEN 4
         WHEN LIFETIME_VALUE >= 20000  THEN 3
         WHEN LIFETIME_VALUE >= 5000   THEN 2 ELSE 1 END       AS M_SCORE,
    -- Segment
    CASE
        WHEN DAYS_INACTIVE <= 30  AND TOTAL_VISITS >= 6  AND LIFETIME_VALUE >= 20000 THEN 'CHAMPION'
        WHEN DAYS_INACTIVE <= 60  AND TOTAL_VISITS >= 4  AND LIFETIME_VALUE >= 10000 THEN 'LOYAL'
        WHEN DAYS_INACTIVE <= 30  AND TOTAL_VISITS <= 2                              THEN 'NEW CUSTOMER'
        WHEN DAYS_INACTIVE BETWEEN 61 AND 120 AND TOTAL_VISITS >= 4                 THEN 'AT RISK'
        WHEN DAYS_INACTIVE > 120 AND TOTAL_VISITS >= 3                              THEN 'LOST'
        WHEN DAYS_INACTIVE > 180                                                     THEN 'INACTIVE'
        WHEN LIFETIME_VALUE >= 50000                                                 THEN 'HIGH VALUE'
        ELSE 'REGULAR'
    END                                                          AS CUSTOMER_SEGMENT,
    -- Promotion suggestion
    CASE
        WHEN DAYS_INACTIVE > 180                                         THEN 'WE MISS YOU - 15% OFF'
        WHEN DAYS_INACTIVE BETWEEN 91 AND 180                           THEN 'COME BACK OFFER - 10% OFF'
        WHEN LIFETIME_VALUE >= 50000 AND DAYS_INACTIVE <= 30            THEN 'VIP REWARD - SPECIAL GIFT'
        WHEN TOTAL_VISITS >= 12                                          THEN 'LOYALTY BONUS - EXTRA POINTS'
        WHEN TOTAL_VISITS = 1                                            THEN 'WELCOME BACK - 5% NEXT VISIT'
        ELSE 'STANDARD OFFER'
    END                                                          AS PROMO_SUGGESTION,
    -- Birthday flag
    CASE WHEN DATEOFBIRTH IS NOT NULL
              AND MONTH(DATEOFBIRTH)=MONTH(GETDATE())
              AND DAY(DATEOFBIRTH) BETWEEN DAY(GETDATE()) AND DAY(GETDATE())+7
         THEN 1 ELSE 0 END                                     AS BIRTHDAY_THIS_WEEK
FROM BASE
