-- B6. SALES vs PURCHASE COMPARISON
-- ----------------------------------------------------------------
IF OBJECT_ID('dbo.VW_RPT_SALES_VS_PURCHASE','V') IS NOT NULL DROP VIEW dbo.VW_RPT_SALES_VS_PURCHASE
GO
CREATE VIEW dbo.VW_RPT_SALES_VS_PURCHASE AS
WITH SAL AS (
    SELECT SH_DEPT_CODE AS DEPT_CODE,
           DATEPART(YEAR,BILL_DATE) AS YR, DATEPART(MONTH,BILL_DATE) AS MO,
           DATENAME(MONTH,BILL_DATE) AS MONTH_NAME,
           SUM(ISNULL(GRAND_TOTAL,0)) AS SALES_VALUE,
           COUNT(BILL_NO) AS SALES_BILLS
    FROM dbo.SALES_HDR WHERE ISNULL(ISCANCELLED,0)=0
    GROUP BY SH_DEPT_CODE, DATEPART(YEAR,BILL_DATE), DATEPART(MONTH,BILL_DATE), DATENAME(MONTH,BILL_DATE)
),
PUR AS (
    SELECT GH_DEPT_CODE AS DEPT_CODE,
           DATEPART(YEAR,GRN_DATE) AS YR, DATEPART(MONTH,GRN_DATE) AS MO,
           SUM(ISNULL(GRANDTOTAL,0)) AS PURCHASE_VALUE,
           COUNT(GRN_NO) AS PURCHASE_GRNS
    FROM dbo.GRN_HDR WHERE ISNULL(ISCANCELLED,0)=0
    GROUP BY GH_DEPT_CODE, DATEPART(YEAR,GRN_DATE), DATEPART(MONTH,GRN_DATE)
),
RTN AS (
    SELECT SRH_DEPT_CODE AS DEPT_CODE,
           DATEPART(YEAR,BILL_RTN_DATE) AS YR, DATEPART(MONTH,BILL_RTN_DATE) AS MO,
           SUM(ISNULL(GRAND_TOTAL,0)) AS RETURN_VALUE
    FROM dbo.SALES_RETURN_HDR
    GROUP BY SRH_DEPT_CODE, DATEPART(YEAR,BILL_RTN_DATE), DATEPART(MONTH,BILL_RTN_DATE)
)
SELECT S.DEPT_CODE, S.YR AS YEAR, S.MO AS MONTH, S.MONTH_NAME,
       ISNULL(S.SALES_VALUE,0)     AS SALES_VALUE,
       ISNULL(S.SALES_BILLS,0)     AS SALES_BILLS,
       ISNULL(P.PURCHASE_VALUE,0)  AS PURCHASE_VALUE,
       ISNULL(P.PURCHASE_GRNS,0)   AS PURCHASE_GRNS,
       ISNULL(R.RETURN_VALUE,0)    AS RETURN_VALUE,
       ISNULL(S.SALES_VALUE,0) - ISNULL(P.PURCHASE_VALUE,0) AS NET_MARGIN,
       ISNULL(S.SALES_VALUE,0) - ISNULL(R.RETURN_VALUE,0)   AS NET_SALES,
       CASE WHEN ISNULL(P.PURCHASE_VALUE,0)>0
            THEN (ISNULL(S.SALES_VALUE,0)-ISNULL(P.PURCHASE_VALUE,0))/ISNULL(P.PURCHASE_VALUE,0)*100
            ELSE 0 END AS GROSS_MARGIN_PCT
FROM SAL S
LEFT JOIN PUR P ON S.DEPT_CODE=P.DEPT_CODE AND S.YR=P.YR AND S.MO=P.MO
LEFT JOIN RTN R ON S.DEPT_CODE=R.DEPT_CODE AND S.YR=R.YR AND S.MO=R.MO
GO

-- ----------------------------------------------------------------
-- B7. DAILY BUSINESS DASHBOARD VIEW
-- ----------------------------------------------------------------
IF OBJECT_ID('dbo.VW_RPT_DASHBOARD','V') IS NOT NULL DROP VIEW dbo.VW_RPT_DASHBOARD
GO
CREATE VIEW dbo.VW_RPT_DASHBOARD AS
WITH TODAY_SALES AS (
    SELECT SH_DEPT_CODE AS DEPT_CODE,
           COUNT(BILL_NO) AS TODAY_BILLS,
           SUM(ISNULL(GRAND_TOTAL,0)) AS TODAY_SALES,
           SUM(ISNULL(DISC_AMOUNT,0)) AS TODAY_DISCOUNT,
           AVG(ISNULL(GRAND_TOTAL,0)) AS TODAY_AVG_BILL,
           SUM(ISNULL(RedeemAmt,0)) AS TODAY_REDEEMED
    FROM dbo.SALES_HDR
    WHERE CONVERT(DATE,BILL_DATE)=CONVERT(DATE,GETDATE()) AND ISNULL(ISCANCELLED,0)=0
    GROUP BY SH_DEPT_CODE
),
YESTERDAY_SALES AS (
    SELECT SH_DEPT_CODE AS DEPT_CODE,
           COUNT(BILL_NO) AS YEST_BILLS,
           SUM(ISNULL(GRAND_TOTAL,0)) AS YEST_SALES
    FROM dbo.SALES_HDR
    WHERE CONVERT(DATE,BILL_DATE)=CONVERT(DATE,DATEADD(DAY,-1,GETDATE())) AND ISNULL(ISCANCELLED,0)=0
    GROUP BY SH_DEPT_CODE
),
MTD AS (
    SELECT SH_DEPT_CODE AS DEPT_CODE,
           SUM(ISNULL(GRAND_TOTAL,0)) AS MTD_SALES,
           COUNT(BILL_NO) AS MTD_BILLS
    FROM dbo.SALES_HDR
    WHERE MONTH(BILL_DATE)=MONTH(GETDATE()) AND YEAR(BILL_DATE)=YEAR(GETDATE()) AND ISNULL(ISCANCELLED,0)=0
    GROUP BY SH_DEPT_CODE
),
STOCK_ALERTS AS (
    SELECT COUNT(*) AS LOW_STOCK_ITEMS
    FROM dbo.ITEM_MST
    WHERE ISNULL(QOH,0) <= ISNULL(REORDER_LVL,0) AND ISNULL(Discontinue,0)=0
)
SELECT
    T.DEPT_CODE,
    ISNULL(T.TODAY_BILLS,0)     AS TODAY_BILLS,
    ISNULL(T.TODAY_SALES,0)     AS TODAY_SALES,
    ISNULL(T.TODAY_DISCOUNT,0)  AS TODAY_DISCOUNT,
    ISNULL(T.TODAY_AVG_BILL,0)  AS TODAY_AVG_BILL,
    ISNULL(T.TODAY_REDEEMED,0)  AS TODAY_REDEEMED,
    ISNULL(Y.YEST_BILLS,0)      AS YEST_BILLS,
    ISNULL(Y.YEST_SALES,0)      AS YEST_SALES,
    ISNULL(M.MTD_SALES,0)       AS MTD_SALES,
    ISNULL(M.MTD_BILLS,0)       AS MTD_BILLS,
    -- Growth vs yesterday
    CASE WHEN ISNULL(Y.YEST_SALES,0)>0
         THEN (ISNULL(T.TODAY_SALES,0)-ISNULL(Y.YEST_SALES,0))/ISNULL(Y.YEST_SALES,0)*100
         ELSE 0 END              AS DOD_GROWTH_PCT,
    SA.LOW_STOCK_ITEMS,
    GETDATE()                    AS DASHBOARD_TIME
FROM TODAY_SALES T
LEFT JOIN YESTERDAY_SALES Y ON T.DEPT_CODE=Y.DEPT_CODE
LEFT JOIN MTD M ON T.DEPT_CODE=M.DEPT_CODE
CROSS JOIN STOCK_ALERTS SA
GO

