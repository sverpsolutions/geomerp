-- ----------------------------------------------------------------
-- B9. EXCEPTION REPORT - Abnormal transactions, anomalies
-- ----------------------------------------------------------------
IF OBJECT_ID('dbo.VW_RPT_EXCEPTIONS','V') IS NOT NULL DROP VIEW dbo.VW_RPT_EXCEPTIONS
GO
CREATE VIEW dbo.VW_RPT_EXCEPTIONS AS
-- Abnormally high bills (> 3x average)
SELECT 'HIGH BILL AMOUNT' AS EXCEPTION_TYPE,
       H.SH_DEPT_CODE AS DEPT_CODE,
       CAST(H.BILL_NO AS VARCHAR) AS REFERENCE_NO,
       CONVERT(DATE,H.BILL_DATE) AS TXN_DATE,
       H.CUSTOMER AS CUSTOMER_NAME,
       'Bill amount ' + CAST(ISNULL(H.GRAND_TOTAL,0) AS VARCHAR) + ' is unusually high' AS EXCEPTION_DETAIL,
       ISNULL(H.GRAND_TOTAL,0) AS AMOUNT,
       'HIGH' AS SEVERITY
FROM dbo.SALES_HDR H
WHERE ISNULL(H.ISCANCELLED,0)=0
  AND ISNULL(H.GRAND_TOTAL,0) > (SELECT AVG(ISNULL(GRAND_TOTAL,0))*3 FROM dbo.SALES_HDR WHERE ISNULL(ISCANCELLED,0)=0)

UNION ALL

-- Negative stock items
SELECT 'NEGATIVE STOCK' AS EXCEPTION_TYPE,
       '' AS DEPT_CODE,
       CAST(ITEM_CODE AS VARCHAR) AS REFERENCE_NO,
       GETDATE() AS TXN_DATE,
       ITEM_NAME AS CUSTOMER_NAME,
       'Negative QOH: ' + CAST(ISNULL(QOH,0) AS VARCHAR) AS EXCEPTION_DETAIL,
       ISNULL(QOH,0)*ISNULL(CP,0) AS AMOUNT,
       'CRITICAL' AS SEVERITY
FROM dbo.ITEM_MST WHERE ISNULL(QOH,0) < 0 AND ISNULL(Discontinue,0)=0

UNION ALL

-- Zero-cost items sold (CP=0 but sold)
SELECT 'ZERO COST ITEM SOLD' AS EXCEPTION_TYPE,
       D.SD_DEPT_CODE AS DEPT_CODE,
       CAST(D.BILL_NO AS VARCHAR) AS REFERENCE_NO,
       CONVERT(DATE,H.BILL_DATE) AS TXN_DATE,
       I.ITEM_NAME AS CUSTOMER_NAME,
       'Item sold with zero cost price - profit % may be wrong' AS EXCEPTION_DETAIL,
       ISNULL(D.AMOUNT,0) AS AMOUNT,
       'MEDIUM' AS SEVERITY
FROM dbo.SALES_DTL D
INNER JOIN dbo.SALES_HDR H ON D.BILL_NO=H.BILL_NO AND D.SD_DEPT_CODE=H.SH_DEPT_CODE
LEFT  JOIN dbo.ITEM_MST I ON D.SERVICEORPRODUCTCODE=I.ITEM_CODE
WHERE ISNULL(D.ORG_CP,0)=0 AND ISNULL(D.AMOUNT,0)>0
  AND ISNULL(H.ISCANCELLED,0)=0 AND H.BILL_DATE >= DATEADD(DAY,-30,GETDATE())

UNION ALL

-- High discount bills (>30%)
SELECT 'EXCESSIVE DISCOUNT' AS EXCEPTION_TYPE,
       H.SH_DEPT_CODE AS DEPT_CODE,
       CAST(H.BILL_NO AS VARCHAR) AS REFERENCE_NO,
       CONVERT(DATE,H.BILL_DATE) AS TXN_DATE,
       H.CUSTOMER AS CUSTOMER_NAME,
       'Discount ' + CAST(CAST(ISNULL(H.DISC_PER,0) AS DECIMAL(5,1)) AS VARCHAR) + '% exceeds threshold' AS EXCEPTION_DETAIL,
       ISNULL(H.DISC_AMOUNT,0) AS AMOUNT,
       'MEDIUM' AS SEVERITY
FROM dbo.SALES_HDR H
WHERE ISNULL(H.ISCANCELLED,0)=0
  AND ISNULL(H.DISC_PER,0) > 30
  AND H.BILL_DATE >= DATEADD(DAY,-30,GETDATE())
GO

