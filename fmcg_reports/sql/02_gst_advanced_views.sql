-- ----------------------------------------------------------------
-- B4. FAST/SLOW MOVING ITEMS
-- ----------------------------------------------------------------
IF OBJECT_ID('dbo.VW_RPT_ITEM_VELOCITY','V') IS NOT NULL DROP VIEW dbo.VW_RPT_ITEM_VELOCITY
GO
CREATE VIEW dbo.VW_RPT_ITEM_VELOCITY AS
WITH ITEM_SALES AS (
    SELECT
        D.SERVICEORPRODUCTCODE AS ITEM_CODE,
        SUM(ISNULL(D.QTY,0)) AS QTY_SOLD_90D,
        COUNT(DISTINCT H.BILL_NO) AS BILL_COUNT_90D,
        SUM(ISNULL(D.AMOUNT,0)) AS SALES_VALUE_90D,
        MAX(CONVERT(DATE,H.BILL_DATE)) AS LAST_SOLD_DATE,
        DATEDIFF(DAY, MAX(H.BILL_DATE), GETDATE()) AS DAYS_SINCE_SOLD
    FROM dbo.SALES_HDR H
    INNER JOIN dbo.SALES_DTL D ON H.BILL_NO=D.BILL_NO AND H.SH_DEPT_CODE=D.SD_DEPT_CODE
    WHERE ISNULL(H.ISCANCELLED,0)=0
      AND H.BILL_DATE >= DATEADD(DAY,-90,GETDATE())
      AND D.SALES_ITEM_TYPE='P'
    GROUP BY D.SERVICEORPRODUCTCODE
)
SELECT
    I.ITEM_CODE, I.ITEM_NAME, I.EAN_CODE,
    CAT.Category_Desc AS CATEGORY, BRD.Brand_Name AS BRAND,
    S.SUPPLIER_NAME,
    ISNULL(I.QOH,0)               AS STOCK_QTY,
    ISNULL(I.CP,0)                AS COST_PRICE,
    ISNULL(I.MRP,0)               AS MRP,
    ISNULL(I.QOH,0)*ISNULL(I.CP,0) AS STOCK_VALUE,
    ISNULL(IS2.QTY_SOLD_90D,0)   AS QTY_SOLD_90D,
    ISNULL(IS2.BILL_COUNT_90D,0) AS BILLS_90D,
    ISNULL(IS2.SALES_VALUE_90D,0) AS SALES_VALUE_90D,
    IS2.LAST_SOLD_DATE,
    ISNULL(IS2.DAYS_SINCE_SOLD,999) AS DAYS_SINCE_LAST_SOLD,
    -- Velocity classification
    CASE
        WHEN ISNULL(IS2.QTY_SOLD_90D,0) = 0 THEN 'NON-MOVING'
        WHEN ISNULL(IS2.QTY_SOLD_90D,0)/90.0 >= 3 THEN 'FAST MOVING'
        WHEN ISNULL(IS2.QTY_SOLD_90D,0)/90.0 >= 1 THEN 'MEDIUM MOVING'
        WHEN ISNULL(IS2.QTY_SOLD_90D,0)/90.0 >= 0.1 THEN 'SLOW MOVING'
        ELSE 'VERY SLOW'
    END AS VELOCITY,
    -- Days of stock remaining
    CASE WHEN ISNULL(IS2.QTY_SOLD_90D,0)>0
         THEN ISNULL(I.QOH,0) / (ISNULL(IS2.QTY_SOLD_90D,0)/90.0)
         ELSE 9999 END AS DAYS_STOCK_REMAINING
FROM dbo.ITEM_MST I
LEFT JOIN ITEM_SALES IS2 ON I.ITEM_CODE=IS2.ITEM_CODE
LEFT JOIN dbo.Category_Mst CAT ON I.CATEGORY_CODE=CAT.Category_Code
LEFT JOIN dbo.Brand_Master BRD ON I.BRAND_CODE=BRD.Brand_Code
LEFT JOIN dbo.SUPPLIER_MST S   ON I.SUPPLIER_CODE=S.SUPPLIER_CODE
WHERE ISNULL(I.Discontinue,0)=0
GO

