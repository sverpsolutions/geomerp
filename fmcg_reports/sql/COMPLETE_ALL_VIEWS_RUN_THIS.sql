-- 24. CUSTOMER SEGMENTS (RFM-style)
-- ────────────────────────────────────────────────────────────────
IF OBJECT_ID('dbo.VW_RPT_CUSTOMER_SEGMENTS','V') IS NOT NULL DROP VIEW dbo.VW_RPT_CUSTOMER_SEGMENTS
GO
CREATE VIEW dbo.VW_RPT_CUSTOMER_SEGMENTS AS
SELECT
    H.CUSTOMER_CODE,
    CM.CUSTOMER_NAME,
    CM.OFFICE1_PHONE                   AS MOBILE,
    CM.OFFICE1_EMAIL_ID               AS EMAIL,
    ISNULL(CM.VIP_CUSTOMER,0)         AS IS_VIP,
    CM.OFFICE1_CITY                   AS CITY,
    COUNT(DISTINCT H.BILL_NO)          AS TOTAL_VISITS,
    SUM(ISNULL(H.GRAND_TOTAL,0))      AS LIFETIME_VALUE,
    AVG(ISNULL(H.GRAND_TOTAL,0))      AS AVG_BILL_VALUE,
    MAX(CONVERT(DATE,H.BILL_DATE))     AS LAST_VISIT,
    MIN(CONVERT(DATE,H.BILL_DATE))     AS FIRST_VISIT,
    DATEDIFF(DAY,MAX(CONVERT(DATE,H.BILL_DATE)),CAST(GETDATE() AS DATE)) AS DAYS_INACTIVE,
    ISNULL(CM.BALANCE_POINTS,0)       AS LOYALTY_POINTS,
    -- Segment logic
    CASE
        WHEN DATEDIFF(DAY,MAX(CONVERT(DATE,H.BILL_DATE)),CAST(GETDATE() AS DATE))<=30
             AND SUM(ISNULL(H.GRAND_TOTAL,0))>=10000 THEN 'CHAMPION'
        WHEN DATEDIFF(DAY,MAX(CONVERT(DATE,H.BILL_DATE)),CAST(GETDATE() AS DATE))<=30 THEN 'LOYAL'
        WHEN DATEDIFF(DAY,MAX(CONVERT(DATE,H.BILL_DATE)),CAST(GETDATE() AS DATE))<=90
             AND SUM(ISNULL(H.GRAND_TOTAL,0))>=5000 THEN 'POTENTIAL LOYALIST'
        WHEN DATEDIFF(DAY,MAX(CONVERT(DATE,H.BILL_DATE)),CAST(GETDATE() AS DATE))<=90 THEN 'RECENT'
        WHEN DATEDIFF(DAY,MAX(CONVERT(DATE,H.BILL_DATE)),CAST(GETDATE() AS DATE))<=180 THEN 'AT RISK'
        WHEN DATEDIFF(DAY,MAX(CONVERT(DATE,H.BILL_DATE)),CAST(GETDATE() AS DATE))<=365 THEN 'DORMANT'
        ELSE 'LOST'
    END AS CUSTOMER_SEGMENT
FROM dbo.SALES_HDR H
INNER JOIN dbo.CUSTOMER_MST CM ON H.CUSTOMER_CODE=CM.CUSTOMER_CODE
WHERE ISNULL(H.ISCANCELLED,0)=0
  AND H.CUSTOMER_CODE IS NOT NULL AND H.CUSTOMER_CODE>0
GROUP BY H.CUSTOMER_CODE,CM.CUSTOMER_NAME,CM.OFFICE1_PHONE,
         CM.OFFICE1_EMAIL_ID,ISNULL(CM.VIP_CUSTOMER,0),
         CM.OFFICE1_CITY,ISNULL(CM.BALANCE_POINTS,0)
GO

-- ────────────────────────────────────────────────────────────────
-- 25. ITEM VELOCITY (fast/slow moving)
-- ────────────────────────────────────────────────────────────────
IF OBJECT_ID('dbo.VW_RPT_ITEM_VELOCITY','V') IS NOT NULL DROP VIEW dbo.VW_RPT_ITEM_VELOCITY
GO
CREATE VIEW dbo.VW_RPT_ITEM_VELOCITY AS
SELECT
    D.SD_DEPT_CODE                     AS DEPT_CODE,
    D.SERVICEORPRODUCTCODE             AS ITEM_CODE,
    I.ITEM_NAME,
    I.EAN_CODE,
    CAT.Category_Desc                  AS CATEGORY,
    BRD.Brand_Name                     AS BRAND,
    S.SUPPLIER_NAME,
    ISNULL(I.QOH,0)                   AS CURRENT_STOCK,
    COUNT(DISTINCT H.BILL_NO)          AS BILLS_COUNT,
    COUNT(DISTINCT CONVERT(DATE,H.BILL_DATE)) AS DAYS_SOLD,
    SUM(ISNULL(D.QTY,0))             AS TOTAL_QTY_SOLD,
    SUM(ISNULL(D.AMOUNT,0))          AS TOTAL_REVENUE,
    AVG(ISNULL(D.QTY,0))             AS AVG_QTY_PER_BILL,
    MAX(CONVERT(DATE,H.BILL_DATE))    AS LAST_SOLD_DATE,
    DATEDIFF(DAY,MAX(CONVERT(DATE,H.BILL_DATE)),CAST(GETDATE() AS DATE)) AS DAYS_SINCE_SOLD,
    -- Daily average sales
    CASE WHEN DATEDIFF(DAY,MIN(CONVERT(DATE,H.BILL_DATE)),MAX(CONVERT(DATE,H.BILL_DATE)))>0
         THEN SUM(ISNULL(D.QTY,0)) / DATEDIFF(DAY,MIN(CONVERT(DATE,H.BILL_DATE)),CAST(GETDATE() AS DATE))
         ELSE SUM(ISNULL(D.QTY,0)) END AS DAILY_AVG_SALES,
    -- Velocity classification
    CASE
        WHEN SUM(ISNULL(D.QTY,0)) >= 100 AND DATEDIFF(DAY,MAX(CONVERT(DATE,H.BILL_DATE)),CAST(GETDATE() AS DATE))<=30 THEN 'FAST MOVING'
        WHEN SUM(ISNULL(D.QTY,0)) >= 20  AND DATEDIFF(DAY,MAX(CONVERT(DATE,H.BILL_DATE)),CAST(GETDATE() AS DATE))<=60 THEN 'MEDIUM MOVING'
        WHEN DATEDIFF(DAY,MAX(CONVERT(DATE,H.BILL_DATE)),CAST(GETDATE() AS DATE))>180 THEN 'DEAD STOCK'
        ELSE 'SLOW MOVING'
    END AS VELOCITY
FROM dbo.SALES_DTL D
INNER JOIN dbo.SALES_HDR H      ON D.BILL_NO=H.BILL_NO AND D.SD_DEPT_CODE=H.SH_DEPT_CODE
LEFT  JOIN dbo.ITEM_MST I       ON D.SERVICEORPRODUCTCODE=I.ITEM_CODE
LEFT  JOIN dbo.Category_Mst CAT ON I.CATEGORY_CODE=CAT.Category_Code
LEFT  JOIN dbo.Brand_Master BRD ON I.BRAND_CODE=BRD.Brand_Code
LEFT  JOIN dbo.SUPPLIER_MST S   ON I.SUPPLIER_CODE=S.SUPPLIER_CODE
WHERE ISNULL(H.ISCANCELLED,0)=0 AND D.SALES_ITEM_TYPE='P'
GROUP BY D.SD_DEPT_CODE,D.SERVICEORPRODUCTCODE,I.ITEM_NAME,I.EAN_CODE,
         CAT.Category_Desc,BRD.Brand_Name,S.SUPPLIER_NAME,ISNULL(I.QOH,0)
GO

-- ────────────────────────────────────────────────────────────────
-- 26. PROFITABILITY (item + customer wise)
-- ────────────────────────────────────────────────────────────────
IF OBJECT_ID('dbo.VW_RPT_PROFITABILITY','V') IS NOT NULL DROP VIEW dbo.VW_RPT_PROFITABILITY
GO
CREATE VIEW dbo.VW_RPT_PROFITABILITY AS
SELECT
    H.SH_DEPT_CODE                     AS DEPT_CODE,
    DATEPART(YEAR,  H.BILL_DATE)      AS YEAR,
    DATEPART(MONTH, H.BILL_DATE)      AS MONTH,
    DATENAME(MONTH, H.BILL_DATE)      AS MONTH_NAME,
    D.SERVICEORPRODUCTCODE             AS ITEM_CODE,
    I.ITEM_NAME,
    CAT.Category_Desc                  AS CATEGORY,
    BRD.Brand_Name                     AS BRAND,
    H.CUSTOMER_CODE,
    H.CUSTOMER                         AS CUSTOMER_NAME,
    SUM(ISNULL(D.QTY,0))             AS QTY_SOLD,
    SUM(ISNULL(D.AMOUNT,0))          AS REVENUE,
    SUM(ISNULL(D.ORG_CP,0)*ISNULL(D.QTY,0)) AS COST_OF_GOODS,
    SUM(ISNULL(D.DISC_AMOUNT,0))     AS DISCOUNT_GIVEN,
    SUM(ISNULL(D.AMOUNT,0)) - SUM(ISNULL(D.ORG_CP,0)*ISNULL(D.QTY,0)) AS GROSS_PROFIT,
    CASE WHEN SUM(ISNULL(D.AMOUNT,0))>0
         THEN (SUM(ISNULL(D.AMOUNT,0))-SUM(ISNULL(D.ORG_CP,0)*ISNULL(D.QTY,0)))
              / SUM(ISNULL(D.AMOUNT,0)) * 100
         ELSE 0 END                    AS MARGIN_PCT,
    SUM(ISNULL(CAST(D.TAX_AMOUNT AS MONEY),0)) AS GST_COLLECTED
FROM dbo.SALES_HDR H
INNER JOIN dbo.SALES_DTL D      ON H.BILL_NO=D.BILL_NO AND H.SH_DEPT_CODE=D.SD_DEPT_CODE
LEFT  JOIN dbo.ITEM_MST I       ON D.SERVICEORPRODUCTCODE=I.ITEM_CODE
LEFT  JOIN dbo.Category_Mst CAT ON I.CATEGORY_CODE=CAT.Category_Code
LEFT  JOIN dbo.Brand_Master BRD ON I.BRAND_CODE=BRD.Brand_Code
WHERE ISNULL(H.ISCANCELLED,0)=0 AND D.SALES_ITEM_TYPE='P'
GROUP BY H.SH_DEPT_CODE,DATEPART(YEAR,H.BILL_DATE),DATEPART(MONTH,H.BILL_DATE),
         DATENAME(MONTH,H.BILL_DATE),D.SERVICEORPRODUCTCODE,I.ITEM_NAME,
         CAT.Category_Desc,BRD.Brand_Name,H.CUSTOMER_CODE,H.CUSTOMER
GO

-- ────────────────────────────────────────────────────────────────
-- 27. SALES vs PURCHASE (month comparison)
-- ────────────────────────────────────────────────────────────────
IF OBJECT_ID('dbo.VW_RPT_SALES_VS_PURCHASE','V') IS NOT NULL DROP VIEW dbo.VW_RPT_SALES_VS_PURCHASE
